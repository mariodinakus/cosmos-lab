"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path");
const G=require("../gravity-core.js"),root=path.resolve(__dirname,"..");
assert.equal(G.MODES.length,3);
assert.equal(new Set(G.MODES.map(m=>m.id)).size,3);
assert.equal(G.binaryEntropy(.5),1);
assert.equal(G.binaryEntropy(0),0);
assert.equal(G.binaryEntropy(1),0);
assert(Math.abs(G.binaryEntropy(.18)-G.binaryEntropy(.82))<1e-13);
const chain=[{a:0,b:1,p:.5},{a:1,b:2,p:.5}];
assert.equal(G.boundaryEntropy(chain,[true,false,false]),1);
assert.equal(G.boundaryEntropy(chain,[true,true,false]),1);
assert.equal(G.boundaryEntropy(chain,[true,true,true]),0);
assert.equal(G.minSTCut(chain,3,0,2).value,1);
assert.equal(G.shortestLinkPath(chain,3,0,2).path.join(","),"0,1,2");
const m=G.make("links",{strength:.5,disorder:0,bridges:0,drive:0},42);
const original=m.metric().value;
for(let k=0;k<120;k++)m.step();
assert(Math.abs(m.metric().value-original)<1e-10,"constant links when drive disabled");
const p0=m.state.region.slice();
m.interact(m.state.nodes[0].x,m.state.nodes[0].y);
assert.notDeepEqual(m.state.region,p0,"region click toggles");
m.interact(.5,.18,true);
assert(Number.isFinite(m.metric().value),"edge edit remains finite");
const a={x:0,t:0},b={x:.2,t:.3},c={x:.25,t:.8};
assert(G.causallyBefore(a,b,1));
assert(G.causallyBefore(b,c,1));
assert(G.causallyBefore(a,c,1),"causal order transitive in Minkowski");
assert(!G.causallyBefore(c,a,1),"asymmetry");
assert(!G.causallyBefore({x:0,t:0},{x:2,t:.3},1),"outside light cone");
const chainEvents=[{id:0,x:0,t:0},{id:1,x:0,t:.2},{id:2,x:0,t:.5},{id:3,x:0,t:.9}];
assert.equal(G.causalStats(chainEvents,1).maxDepth,4);
assert.equal(G.causalInterval(chainEvents,1,0,3).count,2);
assert.equal(G.causalInterval(chainEvents,1,3,0).valid,false);
const causal=G.make("causal",{events:90,lightspeed:1},111);
for(let k=0;k<250;k++)causal.step();
assert.equal(causal.state.visible,90);
assert(causal.metric().value>=1&&causal.metric().value<=90);
const weights=Array(4).fill(.5);
assert.deepEqual(G.pageCurve(weights).map(q=>q.entropy),[0,1,2,3,4,3,2,1,0]);
for(const k of [0,1,4,8])assert.equal(G.pageEntropy(weights,k),G.pageEntropy(weights,8-k));
const p=G.make("page",{qubits:16,strength:.5,disorder:0},1234);
for(let k=0;k<8;k++)p.step();
assert.equal(p.metric().value,8);
p.interact(.25,.5);assert.equal(p.state.k,4);
p.step();assert.equal(p.state.k,5);
for(const mode of G.MODES){
 const a=G.make(mode.id,{},12345),b=G.make(mode.id,{},12345);
 assert(mode.what.length>50&&mode.limit.length>70,mode.id+" scientific caveats");
 for(let k=0;k<130;k++){a.step();b.step();}
 assert(Number.isFinite(a.metric().value)&&a.metric().value>=0,mode.id+" metric");
 assert(Math.abs(a.metric().value-b.metric().value)<1e-9,mode.id+" deterministic replay");
 a.interact(.7,.45);
 assert(Number.isFinite(a.metric().value),mode.id+" finite interaction");
}
const html=fs.readFileSync(path.join(root,"gravity.html"),"utf8");
const ids=["worldCanvas","chartCanvas","modeList","paramList","playButton","stepButton","resetButton","reseedButton","speedInput","saveRun","compareRun","downloadCsv","downloadJson","downloadPng","copyLink"];
for(const id of ids)assert(html.includes('id="'+id+'"'),"Missing UI control "+id);
const js=fs.readFileSync(path.join(root,"gravity.js"),"utf8");
assert.doesNotThrow(()=>new Function(js),"Browser UI script syntax");
assert(!/\beval\s*\(/.test(js),"No evaluation of user-supplied code");
for(const p of ["gravity.js","gravity.css","gravity.html","gravity-core.js"])assert(fs.existsSync(path.join(root,p)),p+" missing");
for(const p of ["index.html","frontier.html","toybox.html","chaos.html","studio.html","observatory.html"])assert(fs.readFileSync(path.join(root,p),"utf8").includes('href="/gravity.html"'),"Navigation missing from "+p);
const config=JSON.parse(fs.readFileSync(path.join(root,"vercel.json"),"utf8"));
assert(config.rewrites.some(r=>r.source==="/gravity"&&r.destination==="/gravity.html"));
console.log("PASS quantum gravity toys: link-cut entropy, shortest paths, causality, Page-like pure pairs, UI, navigation");
