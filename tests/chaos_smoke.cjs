"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const root=path.resolve(__dirname,"..");
const C=require("../chaos-core.js");
assert.equal(C.logistic(4,.5),1);
assert.equal(C.orbit(4,.5,2).length,3);
assert(Math.abs(C.lyapunov(4,.2133,1000,6000)-Math.LN2)<.025,"r=4 expected ln 2, finite-time");
assert(C.lyapunov(2.8,.2133,800,2000)<-.01,"stable region expected negative exponent");
assert.equal(C.approxPeriod(2.8,.2133),1);
assert.equal(C.approxPeriod(3.2,.2133),2);
const pts=C.bifurcation(3.5,4,20,10,300);
assert.equal(pts.length,200);
assert(pts.every(([r,x])=>r>=3.5&&r<=4&&x>=0&&x<=1));
const L=C.exponentCurve(2.7,4,25);
assert.equal(L.length,25);
assert(L.every(p=>Number.isFinite(p.lambda)));
const T=C.twinTrajectory(3.9,.2133,1e-8,100);
assert.equal(T.length,101);
assert(T.every(p=>Number.isFinite(p.separation)&&p.separation>=0&&p.separation<=1));
for(const file of ["chaos.html","chaos.css","chaos.js","chaos-core.js"])assert(fs.existsSync(path.join(root,file)),file);
const html=fs.readFileSync(path.join(root,"chaos.html"),"utf8");
const browser=fs.readFileSync(path.join(root,"chaos.js"),"utf8");
assert.doesNotThrow(()=>new Function(browser),"browser script syntax");
for(const id of ["bifCanvas","lyapCanvas","cobwebCanvas","orbitCanvas","sensitivityCanvas","rInput","xInput","epsInput","playButton","stepButton","resetButton","captureButton","downloadButton","shareButton"])assert(html.includes('id="'+id+'"'),id);
for(const page of ["index.html","studio.html","observatory.html"])assert(fs.readFileSync(path.join(root,page),"utf8").includes('href="/chaos.html"'),"Navigation missing in "+page);
console.log("PASS chaos: logistic map, periods, Lyapunov, bifurcation, sensitivity, syntax, navigation");
